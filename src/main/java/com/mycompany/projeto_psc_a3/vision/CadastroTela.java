    private void cadastrarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cadastrarButtonActionPerformed
        String nome = nomeTextField.getText();
        String sobrenome = sobrenomeTextField.getText();
        String email = emailTextField.getText();
        String cpf = cpfTextField.getText();
        String telefone = telefoneTextField.getText();
        String endereco = enderecoTextField.getText();
        String cep = cepTextField.getText();
        String dia = diaTextField.getText();
        String mes = mesTextField.getText();
        String ano = anoTextField.getText();
        String senha = new String(senhaPasswordField.getPassword());
        String cSenha = new String(confirmacaoSenhaPasswordField.getPassword());
        String nomeCompleto = nome + " " + sobrenome;
        DAO dao = new DAO();
        CalculoIdade ci = new CalculoIdade(dia, mes, ano);
        int idade = ci.getIdade();
        Paciente usuario = new Paciente(nomeCompleto, cpf, telefone, cep, endereco, idade, email, senha);

        try {
            if (nome == null || nome.length() == 0 || sobrenome == null || sobrenome.length() == 0 || senha == null || senha.length() == 0 || cSenha == null || cSenha.length() == 0 || email == null || email.length() == 0 || cpf == null || cpf.length() == 0 || telefone == null || telefone.length() == 0 || dia == null || dia.length() == 0 || mes == null || mes.length() == 0 || ano == null || ano.length() == 0 || endereco == null || endereco.length() == 0 || cep == null || cep.length() == 0) {
                JOptionPane.showMessageDialog(null, "Por favor, preencha todos os campos.");
            } else if (dao.existePaciente(usuario)) {
                JOptionPane.showMessageDialog(null, "O usuário já existe.");
            } else if (!cSenha.equals(senha)) {
                JOptionPane.showMessageDialog(null, "As senhas se diferem, revise os dados e tente novamente.");
            } else if (senha.equals(cSenha)){
                dao.cadastroUsuario(usuario);
                JOptionPane.showMessageDialog(null, "Usuário cadastrado com sucesso!");
                LoginTela lt = new LoginTela();
                lt.setVisible(true);
                this.dispose();
            }
            }catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Falha técnica, tente mais tarde");
            e.printStackTrace();
        }
    }//GEN-LAST:event_cadastrarButtonActionPerformed

