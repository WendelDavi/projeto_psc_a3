    private void entrarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_entrarButtonActionPerformed
        String login = loginTextField.getText();
        String senha = new String(senhaPasswordField.getPassword());

        try {
            Paciente usuario = new Paciente(login, senha);
            DAO dao = new DAO();
            Paciente pacienteLogado = dao.existePaciente(usuario);

            if (pacienteLogado != null) {
                JOptionPane.showMessageDialog(null, "Bem vindo(a)!");
                this.pacienteLogado = pacienteLogado;
                MainLayoutTela ml = new MainLayoutTela();
                ml.setVisible(true);
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(null, "Usuário/senha inválidos");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Problemas técnicos. Tente novamente mais tarde");
            e.printStackTrace();
        }
    }//GEN-LAST:event_entrarButtonActionPerformed

