    private void entrarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_entrarButtonActionPerformed
        String login = loginAdmTextField.getText();
        String senha = new String(senhaAdmPasswordField.getPassword());

        try {
            Administrador usuario = new Administrador(login, senha);
            DAO dao = new DAO();
            if (dao.existeAdm(usuario)) {
                JOptionPane.showMessageDialog(null, "Bem vindo(a)!");
                AdministradorTela at = new AdministradorTela();
                at.setVisible(true);
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(null, "Usuário/senha inválidos");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Problemas técnicos. Tente novamente mais tarde");
            e.printStackTrace();
        }
    }//GEN-LAST:event_entrarButtonActionPerformed

