    private void consultasComboBoxActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_consultasComboBoxActionPerformed

        Consulta consultaSelecionada = (Consulta) consultasComboBox.getSelectedItem();

        if (consultaSelecionada != null) {
            String especialidade = consultaSelecionada.getEspecialidade();
            String data = consultaSelecionada.getData();
            String hora = consultaSelecionada.getHora();
            Double valor = consultaSelecionada.getValor();
            DecimalFormat df = new DecimalFormat("#.00");
            String valorFormatado = df.format(valor);

            // Atualiza os campos de texto
            especialidadeTextField.setText(especialidade);
            dataTextField.setText(data);
            horaTextField.setText(hora);
            valorTextField.setText("R$ " + valorFormatado);
        } else {
            // Tratar o caso em que nenhuma consulta está selecionada
            especialidadeTextField.setText("");
            dataTextField.setText("");
            horaTextField.setText("");
            valorTextField.setText("");
        }

    }//GEN-LAST:event_consultasComboBoxActionPerformed

