    private void agendarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_agendarButtonActionPerformed
        String especialidade = especialidadeTextField.getText();
        String sData = dataTextField.getText();
        String sHora = horaTextField.getText();
        String sCpf = cpfTextField.getText();
        String sValor = valorTextField.getText();

        String valorLimpo = sValor.replace("R$", "").replace(",", ".").trim();
        Double valor = Double.valueOf(valorLimpo);

        if (sCpf.isEmpty() || especialidade.isEmpty() || sData.isEmpty() || sHora.isEmpty() || valorLimpo.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Por favor, selecione uma consulta");
            return;
        }

        try {
            int escolha = JOptionPane.showConfirmDialog(null, "Deseja realmente marcar essa consulta?");
            if (escolha == JOptionPane.YES_OPTION) {

                SimpleDateFormat originalFormat = new SimpleDateFormat("dd/MM/yyyy");
                SimpleDateFormat targetFormat = new SimpleDateFormat("yyyy-MM-dd");
                String dataFormatada = targetFormat.format(originalFormat.parse(sData));

                String dataHora = dataFormatada + " " + sHora + ":00";
                System.out.print("DataHora: " + dataHora);
                Timestamp timestampConsulta = Timestamp.valueOf(dataHora);

                DAO dao = new DAO();
                int pacienteId = dao.obterIdPacientePorCpf(sCpf);
                Agendamento agendamento = new Agendamento(especialidade, timestampConsulta, valor, pacienteId);
                dao.adicionarAgendamento(agendamento);

                Consulta c = new Consulta(dataHora);
                dao.removerConsulta(c);

                JOptionPane.showMessageDialog(null, "Agendamento realizado com sucesso.");
                NovoAgendamentoTela na = new NovoAgendamentoTela();
                na.setVisible(true);
                this.dispose();
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Falha técnica, tente mais tarde");
            e.printStackTrace();
        }

    }//GEN-LAST:event_agendarButtonActionPerformed
