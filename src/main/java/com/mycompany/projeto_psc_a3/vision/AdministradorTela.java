    private void removerAdmButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removerAdmButtonActionPerformed
        String email = loginAdmTextField.getText();

        DAO dao = new DAO();
        Administrador usuario = new Administrador(email);

        try {
            if (email == null || email.length() == 0) {
                JOptionPane.showMessageDialog(null, "Por favor, preencha os campos.");
            } else {
                dao.removerAdm(usuario);
                JOptionPane.showMessageDialog(null, "Administrador removido com sucesso!");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Falha técnica, tente mais tarde");
            e.printStackTrace();
        }
    }//GEN-LAST:event_removerAdmButtonActionPerformed

    private void novoAdmButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_novoAdmButtonActionPerformed
        String login = loginAdmTextField.getText();
        String senha = new String(senhaAdmPasswordField.getPassword());

        DAO dao = new DAO();
        Administrador usuario = new Administrador(login, senha);

        try {
            if (login == null || login.length() == 0 || senha == null || senha.length() == 0) {
                JOptionPane.showMessageDialog(null, "Por favor, preencha os campos.");
            } else {
                dao.cadastroAdm(usuario);
                JOptionPane.showMessageDialog(null, "Usuário cadastrado com sucesso!");
                LoginTela lt = new LoginTela();
                lt.setVisible(true);
                this.dispose();
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Falha técnica, tente mais tarde");
            e.printStackTrace();
        }
    }//GEN-LAST:event_novoAdmButtonActionPerformed

